CREATE TABLE products (
    product_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    sku              VARCHAR2(40 CHAR) NOT NULL,
    product_name     VARCHAR2(160 CHAR) NOT NULL,
    description      VARCHAR2(1000 CHAR),
    unit_price       NUMBER(12,2) NOT NULL,
    currency_code    CHAR(3 CHAR) DEFAULT 'AUD' NOT NULL,
    active_flag      CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    created_at       TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at       TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT products_pk PRIMARY KEY (product_id),
    CONSTRAINT products_sku_uq UNIQUE (sku),
    CONSTRAINT products_sku_ck CHECK (REGEXP_LIKE(sku, '[^[:space:]]')),
    CONSTRAINT products_name_ck CHECK (REGEXP_LIKE(product_name, '[^[:space:]]')),
    CONSTRAINT products_price_ck CHECK (unit_price >= 0),
    CONSTRAINT products_currency_ck CHECK (currency_code = 'AUD'),
    CONSTRAINT products_active_ck CHECK (active_flag IN ('Y', 'N'))
);

CREATE TABLE customers (
    customer_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    email            VARCHAR2(254 CHAR) NOT NULL,
    given_name       VARCHAR2(100 CHAR) NOT NULL,
    family_name      VARCHAR2(100 CHAR) NOT NULL,
    phone            VARCHAR2(40 CHAR),
    created_at       TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at       TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT customers_pk PRIMARY KEY (customer_id),
    CONSTRAINT customers_email_uq UNIQUE (email),
    CONSTRAINT customers_email_ck CHECK (REGEXP_LIKE(email, '[^[:space:]]')),
    CONSTRAINT customers_given_ck CHECK (REGEXP_LIKE(given_name, '[^[:space:]]')),
    CONSTRAINT customers_family_ck CHECK (REGEXP_LIKE(family_name, '[^[:space:]]'))
);

CREATE TABLE inventory (
    product_id          NUMBER NOT NULL,
    on_hand_qty         NUMBER(10,0) DEFAULT 0 NOT NULL,
    reserved_qty        NUMBER(10,0) DEFAULT 0 NOT NULL,
    reorder_level       NUMBER(10,0) DEFAULT 0 NOT NULL,
    updated_at          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT inventory_pk PRIMARY KEY (product_id),
    CONSTRAINT inventory_product_fk FOREIGN KEY (product_id) REFERENCES products(product_id),
    CONSTRAINT inventory_on_hand_ck CHECK (on_hand_qty >= 0),
    CONSTRAINT inventory_reserved_ck CHECK (reserved_qty >= 0 AND reserved_qty <= on_hand_qty),
    CONSTRAINT inventory_reorder_ck CHECK (reorder_level >= 0)
);

CREATE TABLE orders (
    order_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_number        VARCHAR2(30 CHAR) NOT NULL,
    customer_id         NUMBER NOT NULL,
    status              VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    currency_code       CHAR(3 CHAR) DEFAULT 'AUD' NOT NULL,
    subtotal_amount     NUMBER(12,2) DEFAULT 0 NOT NULL,
    total_amount        NUMBER(12,2) DEFAULT 0 NOT NULL,
    placed_at           TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    paid_at             TIMESTAMP(6) WITH TIME ZONE,
    fulfilled_at        TIMESTAMP(6) WITH TIME ZONE,
    cancelled_at        TIMESTAMP(6) WITH TIME ZONE,
    created_at          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT orders_pk PRIMARY KEY (order_id),
    CONSTRAINT orders_number_uq UNIQUE (order_number),
    CONSTRAINT orders_customer_fk FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
    CONSTRAINT orders_status_ck CHECK (status IN ('PENDING', 'CONFIRMED', 'PAID', 'FULFILLED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT orders_currency_ck CHECK (currency_code = 'AUD'),
    CONSTRAINT orders_amounts_ck CHECK (subtotal_amount >= 0 AND total_amount >= 0),
    CONSTRAINT orders_terminal_ts_ck CHECK (
        (status <> 'PAID' OR paid_at IS NOT NULL) AND
        (status <> 'FULFILLED' OR (paid_at IS NOT NULL AND fulfilled_at IS NOT NULL)) AND
        (status <> 'CANCELLED' OR cancelled_at IS NOT NULL)
    )
);

CREATE TABLE order_items (
    order_item_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_id            NUMBER NOT NULL,
    product_id          NUMBER NOT NULL,
    quantity            NUMBER(10,0) NOT NULL,
    unit_price          NUMBER(12,2) NOT NULL,
    line_total          NUMBER(14,2) NOT NULL,
    created_at          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT order_items_pk PRIMARY KEY (order_item_id),
    CONSTRAINT order_items_order_fk FOREIGN KEY (order_id) REFERENCES orders(order_id),
    CONSTRAINT order_items_product_fk FOREIGN KEY (product_id) REFERENCES products(product_id),
    CONSTRAINT order_items_order_product_uq UNIQUE (order_id, product_id),
    CONSTRAINT order_items_link_uq UNIQUE (order_id, product_id, order_item_id),
    CONSTRAINT order_items_qty_ck CHECK (quantity > 0),
    CONSTRAINT order_items_price_ck CHECK (unit_price >= 0),
    CONSTRAINT order_items_total_ck CHECK (line_total = quantity * unit_price)
);

CREATE TABLE reservations (
    reservation_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_item_id      NUMBER NOT NULL,
    order_id           NUMBER NOT NULL,
    product_id         NUMBER NOT NULL,
    quantity           NUMBER(10,0) NOT NULL,
    status             VARCHAR2(12 CHAR) DEFAULT 'CHECKOUT' NOT NULL,
    reserved_at        TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    expires_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    closed_at          TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT reservations_pk PRIMARY KEY (reservation_id),
    CONSTRAINT reservations_order_product_uq UNIQUE (order_id, product_id),
    CONSTRAINT reservations_item_uq UNIQUE (order_item_id),
    CONSTRAINT reservations_item_fk FOREIGN KEY (order_id, product_id, order_item_id)
        REFERENCES order_items (order_id, product_id, order_item_id),
    CONSTRAINT reservations_order_fk FOREIGN KEY (order_id) REFERENCES orders(order_id),
    CONSTRAINT reservations_product_fk FOREIGN KEY (product_id) REFERENCES products(product_id),
    CONSTRAINT reservations_qty_ck CHECK (quantity > 0),
    CONSTRAINT reservations_status_ck CHECK (status IN ('CHECKOUT', 'ALLOCATED', 'RELEASED', 'EXPIRED', 'FULFILLED')),
    CONSTRAINT reservations_window_ck CHECK (expires_at = reserved_at + INTERVAL '10' MINUTE),
    CONSTRAINT reservations_close_ck CHECK (
        (status IN ('CHECKOUT', 'ALLOCATED') AND closed_at IS NULL) OR
        (status IN ('RELEASED', 'EXPIRED', 'FULFILLED') AND closed_at IS NOT NULL)
    )
);

CREATE TABLE payments (
    payment_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_id            NUMBER NOT NULL,
    payment_reference   VARCHAR2(100 CHAR),
    status              VARCHAR2(12 CHAR) DEFAULT 'PENDING' NOT NULL,
    amount              NUMBER(12,2) NOT NULL,
    currency_code       CHAR(3 CHAR) DEFAULT 'AUD' NOT NULL,
    created_at          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    completed_at        TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT payments_pk PRIMARY KEY (payment_id),
    CONSTRAINT payments_order_fk FOREIGN KEY (order_id) REFERENCES orders(order_id),
    CONSTRAINT payments_reference_uq UNIQUE (payment_reference),
    CONSTRAINT payments_status_ck CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'REFUNDED')),
    CONSTRAINT payments_amount_ck CHECK (amount > 0),
    CONSTRAINT payments_currency_ck CHECK (currency_code = 'AUD'),
    CONSTRAINT payments_completion_ck CHECK (
        (status = 'PENDING' AND completed_at IS NULL) OR
        (status IN ('SUCCEEDED', 'FAILED', 'REFUNDED') AND completed_at IS NOT NULL)
    )
);

CREATE TABLE stock_movements (
    stock_movement_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    product_id          NUMBER NOT NULL,
    movement_type       VARCHAR2(12 CHAR) NOT NULL,
    quantity_delta      NUMBER(10,0) NOT NULL,
    reason              VARCHAR2(240 CHAR) NOT NULL,
    reference_type      VARCHAR2(20 CHAR),
    reference_id        NUMBER,
    occurred_at         TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT stock_movements_pk PRIMARY KEY (stock_movement_id),
    CONSTRAINT stock_movements_product_fk FOREIGN KEY (product_id) REFERENCES products(product_id),
    CONSTRAINT stock_movements_type_ck CHECK (movement_type IN ('RECEIPT', 'ADJUSTMENT', 'FULFILMENT', 'RETURN')),
    CONSTRAINT stock_movements_sign_ck CHECK (
        (movement_type IN ('RECEIPT', 'RETURN') AND quantity_delta > 0) OR
        (movement_type = 'ADJUSTMENT' AND quantity_delta <> 0) OR
        (movement_type = 'FULFILMENT' AND quantity_delta < 0)
    ),
    CONSTRAINT stock_movements_reason_ck CHECK (REGEXP_LIKE(reason, '[^[:space:]]')),
    CONSTRAINT stock_movements_ref_ck CHECK ((reference_type IS NULL AND reference_id IS NULL) OR (reference_type IS NOT NULL AND reference_id IS NOT NULL))
);

CREATE INDEX reservations_expiry_ix ON reservations (status, expires_at);
CREATE INDEX stock_movements_product_time_ix ON stock_movements (product_id, occurred_at);
